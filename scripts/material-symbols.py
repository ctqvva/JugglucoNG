#!/usr/bin/env python3
"""Generate Kotlin ImageVectors for the Material Symbols Rounded glyphs listed in
scripts/material-symbols.txt.

Material Symbols is not a Compose artifact, so each glyph is fetched once from
Google Fonts and written as path data into Symbols.kt. The result is used like
material-icons: `Icon(Symbols.MobileArrowDownFilled, ...)`, including from
non-composable code. Network is needed only when regenerating.
"""
import pathlib
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "scripts" / "material-symbols.txt"
OUT = ROOT / "Common/src/main/java/tk/glucodata/ui/symbols/Symbols.kt"
URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{variant}/24px.svg"


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def fetch(name: str, fill: bool) -> str:
    url = URL.format(name=name, variant="fill1" if fill else "default")
    with urllib.request.urlopen(url, timeout=30) as response:
        svg = response.read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        sys.exit(f"no path in {url}")
    return " ".join(paths)


def main() -> None:
    entries = []
    for line in MANIFEST.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, style, *flags = line.split()
        if style not in ("fill", "outline") or any(f != "mirrored" for f in flags):
            sys.exit(f"bad entry: {line}")
        entries.append((name, style == "fill", "mirrored" in flags))
    entries.sort()
    with ThreadPoolExecutor(16) as pool:
        paths = list(pool.map(lambda e: fetch(e[0], e[1]), entries))
    props = []
    for (name, fill, mirrored), data in zip(entries, paths):
        prop = pascal(name) + ("Filled" if fill else "")
        note = ("filled" if fill else "outlined") + (", mirrored in right-to-left layouts" if mirrored else "")
        props.append(
            f'    /** Material Symbols Rounded `{name}`, {note}. */\n'
            f'    val {prop}: ImageVector by lazy {{ symbol("{prop}", "{data}"{", autoMirror = true" if mirrored else ""}) }}\n'
        )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/material-symbols.py from scripts/material-symbols.txt. Do not edit.\n"
        "package tk.glucodata.ui.symbols\n\n"
        "import androidx.compose.ui.graphics.Color\n"
        "import androidx.compose.ui.graphics.SolidColor\n"
        "import androidx.compose.ui.graphics.vector.ImageVector\n"
        "import androidx.compose.ui.graphics.vector.addPathNodes\n"
        "import androidx.compose.ui.unit.dp\n\n"
        "/** Material Symbols Rounded, the app's icon set. Tinted by `Icon` like any ImageVector. */\n"
        "object Symbols {\n" + "\n".join(props) + "}\n\n"
        "// Symbols are drawn on a 960 unit grid whose y runs from -960 to 0.\n"
        "private fun symbol(name: String, pathData: String, autoMirror: Boolean = false): ImageVector =\n"
        "    ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f, autoMirror = autoMirror)\n"
        "        .addGroup(translationY = 960f)\n"
        "        .addPath(addPathNodes(pathData), fill = SolidColor(Color.Black))\n"
        "        .clearGroup()\n"
        "        .build()\n"
    )
    print(f"wrote {len(props)} symbols to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
