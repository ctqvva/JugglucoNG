#!/usr/bin/env python3
"""Generates the Glucy launcher icon, wordmark and banners.

Writes the Android adaptive-icon vectors (background, foreground, monochrome) for the
main app and the second installation (releasedub), plus SVG masters in this folder.
The wordmark is drawn here as monoline strokes; no font file is involved.

    pip install shapely
    python3 docs/brand/build.py                 # run from the repository root

All shapes live on Android's 108 dp adaptive canvas; the visible area is 18..90.
"""
import math
from pathlib import Path
from shapely.geometry import LineString, Point, Polygon

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent

# ---------------------------------------------------------------- geometry ---
KNOTS = [(0, 46), (33, 67), (61, 41), (80, 56), (108, 45)]  # trace: enters high, one dip, settles
NOW_X = 47.5      # the sensor sits on the trace here
W = 7.0           # trace width
R_SENSOR = 8.2    # sensor radius
R_DOT = 1.9       # filament dot
CUT = 1.0         # gap between trace and sensor, so the trace reads as passing behind it
CUT_MONO = 1.1    # slightly wider in the single-colour themed icon


def cubic(segs, n=40):
    pts, cur = [segs[0]], segs[0]
    for c1, c2, p in segs[1:]:
        for i in range(1, n + 1):
            t = i / n; u = 1 - t
            pts.append((u**3*cur[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p[0],
                        u**3*cur[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p[1]))
        cur = p
    return pts


def smooth(points, k=0.38):
    """Horizontal tangents at every knot, so peaks and dips look like a chart."""
    segs = [points[0]]
    for a, b in zip(points, points[1:]):
        dx = (b[0] - a[0]) * k
        segs.append(((a[0] + dx, a[1]), (b[0] - dx, b[1]), b))
    return segs


LINE = LineString(cubic(smooth(KNOTS)))
NOW = min(LINE.coords, key=lambda p: abs(p[0] - NOW_X))
TRACE = LINE.buffer(W / 2, quad_segs=16)
SENSOR = Point(*NOW).buffer(R_SENSOR, quad_segs=48)
DOT = Point(*NOW).buffer(R_DOT, quad_segs=24)
RIM = Point(*NOW).buffer(R_SENSOR - 2.0, quad_segs=48).exterior.buffer(0.45)
BELOW = Polygon(list(LINE.coords) + [(108, 108), (0, 108)]).buffer(0)  # two-tone variant only


def d(geom):
    out = []
    for g in getattr(geom, 'geoms', [geom]):
        g = g.simplify(0.02)
        for ring in [g.exterior, *g.interiors]:
            c = list(ring.coords)[:-1]
            out.append('M' + 'L'.join(f'{x:.2f} {y:.2f}'.replace('.00', '') for x, y in c) + 'Z')
    return ''.join(out)


TRACE_D = d(TRACE.difference(Point(*NOW).buffer(R_SENSOR + CUT, quad_segs=48)))
SENSOR_D, RIM_D, DOT_D, BELOW_D = d(SENSOR), d(RIM), d(DOT), d(BELOW)
MONO_D = d(TRACE.difference(Point(*NOW).buffer(R_SENSOR + CUT_MONO, quad_segs=48))
           .union(SENSOR.difference(RIM).difference(DOT)))

# ------------------------------------------------------------------ colours ---
MAIN = dict(bg='#0D1430', line='#5B86F5', sensor='#F5F7FB', rim='#C9D2E3', dot='#0D1430')
DUB = dict(bg='#1A1236', line='#9C86F6', sensor='#F5F7FB', rim='#C9D2E3', dot='#1A1236')
TWO_TONE = dict(MAIN, bg='#0B1020', below='#121B36', dot='#0B1020')  # branding alternative

# ----------------------------------------------------------------- writers ---
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by docs/brand/build.py. Edit the script, not this file. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n')
ARGB = lambda c: '#FF' + c[1:].upper()


def background_xml(c):
    return HEAD + f'    <path android:pathData="M0 0h108v108h-108z" android:fillColor="{ARGB(c["bg"])}"/>\n</vector>\n'


def foreground_xml(c):
    return HEAD + (
        f'    <path android:fillColor="{ARGB(c["line"])}" android:pathData="{TRACE_D}"/>\n'
        f'    <path android:fillColor="{ARGB(c["sensor"])}" android:pathData="{SENSOR_D}"/>\n'
        f'    <path android:fillColor="{ARGB(c["rim"])}" android:fillType="evenOdd" android:pathData="{RIM_D}"/>\n'
        f'    <path android:fillColor="{ARGB(c["dot"])}" android:pathData="{DOT_D}"/>\n</vector>\n')


MONOCHROME_XML = HEAD + f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{MONO_D}"/>\n</vector>\n'

ADAPTIVE_XML = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                '</adaptive-icon>\n')


def svg(c, view='18 18 72 72', size=512):
    below = f'<path d="{BELOW_D}" fill="{c["below"]}"/>' if 'below' in c else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{size}" height="{size}">'
            f'<rect width="108" height="108" fill="{c["bg"]}"/>{below}'
            f'<path d="{TRACE_D}" fill="{c["line"]}"/><path d="{SENSOR_D}" fill="{c["sensor"]}"/>'
            f'<path d="{RIM_D}" fill="{c["rim"]}" fill-rule="evenodd"/><path d="{DOT_D}" fill="{c["dot"]}"/></svg>\n')


# ---------------------------------------------------------------- wordmark ---
# Monoline lettering with the same round ends as the trace. Units: cap height 100,
# y = 0 at the cap line, y = 100 on the baseline.
WM_STROKE, WM_XHEIGHT, WM_GAP = 17, 70, 13


def _p(cx, cy, r, a):
    return cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))


def _arc(cx, cy, r, a0, a1, ccw=True):
    span = (a0 - a1) % 360 if ccw else (a1 - a0) % 360
    x, y = _p(cx, cy, r, a1)
    return f'A{r:.2f} {r:.2f} 0 {1 if span > 180 else 0} {0 if ccw else 1} {x:.2f} {y:.2f}'


def wordmark():
    """Returns (stroke paths, advance width) for 'Glucy'."""
    h, S, xh, gap = WM_STROKE / 2, WM_STROKE, WM_XHEIGHT, WM_GAP
    paths, x = [], 0.0
    # G: open circle with a short crossbar
    r = 50 - h; cx, cy = x + 50, 50
    sx, sy = _p(cx, cy, r, -42)
    paths.append(f'M{sx:.2f} {sy:.2f}' + _arc(cx, cy, r, -42, 0) + f'L{cx + r * 0.38:.2f} {cy:.2f}')
    x += 100 + gap
    # l
    paths.append(f'M{x + h:.2f} {h:.2f}L{x + h:.2f} {100 - h:.2f}')
    x += S + gap
    # u: two stems and a round bowl; the right stem reaches the baseline
    top, ru = 100 - xh + h, (xh - S) / 2
    left, right, bowl = x + h, x + h + 2 * ru, 100 - h - ru
    paths.append(f'M{left:.2f} {top:.2f}L{left:.2f} {bowl:.2f}' + _arc(left + ru, bowl, ru, 180, 0) + f'L{right:.2f} {top:.2f}')
    paths.append(f'M{right:.2f} {top:.2f}L{right:.2f} {100 - h:.2f}')
    x += 2 * ru + S + gap
    # c
    rc = (xh - S) / 2; ccx, ccy = x + h + rc, 100 - xh / 2
    sx, sy = _p(ccx, ccy, rc, -42)
    paths.append(f'M{sx:.2f} {sy:.2f}' + _arc(ccx, ccy, rc, -42, 42))
    x += 2 * rc + S + gap - rc * (1 - math.cos(math.radians(42))) * 0.6
    # y: the u bowl, with the right stem dropping into a hooked descender
    left, right = x + h, x + h + 2 * ru
    tail_y = 130 - h - ru
    paths.append(f'M{left:.2f} {top:.2f}L{left:.2f} {bowl:.2f}' + _arc(left + ru, bowl, ru, 180, 0))
    paths.append(f'M{right:.2f} {top:.2f}L{right:.2f} {tail_y:.2f}' + _arc(right - ru, tail_y, ru, 0, 135, ccw=False))
    x += 2 * ru + S
    return paths, x


WM_PATHS, WM_WIDTH = wordmark()


def wordmark_svg(color='#0D1430'):
    body = ''.join(f'<path d="{p}"/>' for p in WM_PATHS)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-10 -10 {WM_WIDTH + 20:.0f} 150">'
            f'<g fill="none" stroke="{color}" stroke-width="{WM_STROKE}" stroke-linecap="round" stroke-linejoin="round">{body}</g></svg>\n')


def banner_svg(dark=True, w=1280, h=400):
    page, ink, tile_bg = ('#161E40', '#F2F5FA', MAIN['bg']) if dark else ('#EEF1FA', MAIN['bg'], MAIN['bg'])
    tile, cap = 200, 112
    k, gap = cap / 100, 0.55 * cap
    total = tile + gap + WM_WIDTH * k
    x0, ty = (w - total) / 2, (h - tile) / 2
    s = tile / 72
    icon = (f'<g transform="translate({x0:.1f} {ty:.1f}) scale({s:.4f}) translate(-18 -18)">'
            f'<clipPath id="t"><rect x="18" y="18" width="72" height="72" rx="17"/></clipPath><g clip-path="url(#t)">'
            f'<rect width="108" height="108" fill="{tile_bg}"/><path d="{TRACE_D}" fill="{MAIN["line"]}"/>'
            f'<path d="{SENSOR_D}" fill="{MAIN["sensor"]}"/><path d="{RIM_D}" fill="{MAIN["rim"]}" fill-rule="evenodd"/>'
            f'<path d="{DOT_D}" fill="{MAIN["dot"]}"/></g></g>')
    words = ''.join(f'<path d="{p}"/>' for p in WM_PATHS)
    text = (f'<g transform="translate({x0 + tile + gap:.1f} {h / 2 - cap / 2:.1f}) scale({k:.4f})" fill="none" stroke="{ink}" '
            f'stroke-width="{WM_STROKE}" stroke-linecap="round" stroke-linejoin="round">{words}</g>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">'
            f'<title>Glucy</title><rect width="{w}" height="{h}" fill="{page}"/>{icon}{text}</svg>\n')


def main():
    main_res = ROOT / 'Common/src/main/res'
    dub_res = ROOT / 'Common/src/releasedub/res'
    files = {
        main_res / 'drawable/ic_launcher_background.xml': background_xml(MAIN),
        main_res / 'drawable/ic_launcher_foreground.xml': foreground_xml(MAIN),
        main_res / 'drawable/ic_launcher_monochrome.xml': MONOCHROME_XML,
        main_res / 'mipmap-anydpi-v26/ic_launcher.xml': ADAPTIVE_XML,
        main_res / 'mipmap-anydpi-v26/ic_launcher_round.xml': ADAPTIVE_XML,
        dub_res / 'drawable/ic_launcher_background.xml': background_xml(DUB),
        dub_res / 'drawable/ic_launcher_foreground.xml': foreground_xml(DUB),
        HERE / 'icon.svg': svg(MAIN),
        HERE / 'icon-dub.svg': svg(DUB),
        HERE / 'icon-two-tone.svg': svg(TWO_TONE),
        HERE / 'wordmark.svg': wordmark_svg(),
        HERE / 'wordmark-light.svg': wordmark_svg('#F2F5FA'),
        HERE / 'banner-dark.svg': banner_svg(dark=True),
        HERE / 'banner-light.svg': banner_svg(dark=False),
        HERE / 'monochrome.svg': (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">'
                                  f'<path d="{MONO_D}" fill="#000" fill-rule="evenodd"/></svg>\n'),
    }
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print('wrote', path.relative_to(ROOT))


if __name__ == '__main__':
    main()
