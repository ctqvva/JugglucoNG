    sc=1000 if '1000' in a1 else 1
    c[f'({a1}*V-E*{sc*10})/{sc/10}']=(x*V-E*sc*10)/(sc/10)
    c[f'({a1}*V/10-E*{sc})*{100/sc}']=(x*V/10-E*sc)*(100/sc)
