f=np.float32
c={}
for n,x in {'a*V':A*V,'V*a':V*A}.items():
    c[f'({n}-E*40950)/409.5']=(x-E*40950)/409.5
    c[f'({n}-E*40950)*100/40950']=(x-E*40950)*100/40950
    c[f'({n}-E*40950)/40950*100']=(x-E*40950)/40950*100
    c[f'({n}*100-E*4095000)/40950']=(x*100-E*4095000)/40950
    c[f'({n}/4095-E*10)*10']=(x/4095-E*10)*10
    c[f'({n}/40950-E)*100']=(x/40950-E)*100
    c[f'({n}*1000/4095-E*1000)/10']=(x*1000/4095-E*1000)/10
    c[f'({n}*1000/40950-E*1000)*0.1']=(x*1000/40950-E*1000)*0.1
    c[f'(({n}/4095)*1000-E*1000)/10']=((x/4095)*1000-E*1000)/10
    c[f'(({n}/4095)*1000/10-E*1000/10)']=((x/4095)*1000/10-E*1000/10)
    c[f'({n}/4095*1000-E*1000)*0.1']=(x/4095*1000-E*1000)*0.1
